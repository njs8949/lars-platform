Color lookupPpfColor(String manufacturer, String modelCode) {
  final key = '${manufacturer.toUpperCase()}|${modelCode.toUpperCase()}';
  return _ppfColorByManufacturerAndCode[key] ?? _ppfFallbackChipColor;
}

String? lookupPpfReferenceAsset(String manufacturer, String modelCode, String finish) {
  final brand = manufacturer.toUpperCase();
  final code = modelCode.toLowerCase();
  final finishLower = finish.toLowerCase();

  switch (brand) {
    case 'ULTRAFIT':
      return 'assets/catalog_refs/ultrafit/$code.jpg';
    case 'UPPF':
      if (finishLower.contains('magic')) {
        return 'assets/catalog_refs/uppf/MAGIC PPF.jpg';
      }
      if (finishLower.contains('pattern')) {
        return 'assets/catalog_refs/uppf/TEXTURE PPF.jpg';
      }
      if (finishLower.contains('matte')) {
        return 'assets/catalog_refs/uppf/matte PPF.jpg';
      }
      if (finishLower.contains('clear')) {
        return 'assets/catalog_refs/uppf/CLEAR GLOSS PPF.jpg';
      }
      return 'assets/catalog_refs/uppf/color ppf.jpg';
    case 'G SUIT':
      return 'assets/catalog_refs/gsuit/g-suit-ppf.jpg';
    case 'REFLEX':
      return 'assets/catalog_refs/reflex/reflex-color-ppf.jpg';
    case 'IVIOS':
      if (code.contains('axion') || code.contains('perform')) {
        return 'assets/catalog_refs/ivios/axion-brochure.jpg';
      }
      return 'assets/catalog_refs/ivios/kaizer-brochure.jpg';
    case 'CLIF DESIGNS':
      return 'assets/catalog_refs/clif/ppf-performance.jpg';
    default:
      return null;
  }
}
